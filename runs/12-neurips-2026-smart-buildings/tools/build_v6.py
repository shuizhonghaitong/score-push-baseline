#!/usr/bin/env python3
"""Build self-contained policies/v6_policy.py = V5 + V4g eco-edge hold."""
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
v5 = (root / "policies/v5_policy.py").read_text()
v4g = (root / "policies/v4g_policy.py").read_text()

i = v4g.find("class V4gPolicy")
assert i != -1
v4g_class = v4g[i:]
j = v4g_class.find("    def _band_shift")
assert j != -1
k = v4g_class.rfind("\n")  # last line before standalone alias is inside method
tail = v4g_class.find("V4gPolicyStandalone")
assert tail != -1 and tail > j
band_shift = v4g_class[j:tail].rstrip() + "\n"

out = v5.replace(
    '"""V5 rule-based HVAC policy = V4 + per-zone economic target shift.\n\nGenerated by tools/build_v5.py; do not edit directly.\n"""',
    '"""V6 rule-based HVAC policy = V5 (economic target shift) + V4g (eco-edge hold).\n\nGenerated by tools/build_v6.py; do not edit directly.\n"""',
)

v6 = (
    "\n\nclass V6Policy(V5Policy):\n"
    "    \"\"\"v5 economic target shift + eco-edge hold for long pre-latches.\n\n"
    "    While pre-latched with the comfort start more than fade_h away, hold the\n"
    "    band at the eco edge on the demand side (full at >= full_h), fading back\n"
    "    over the last fade_h. V5's PI then regulates around the shifted band;\n"
    "    its EMA-based extra target shift stays ~0 while the plant holds, so the\n"
    "    two mechanisms are orthogonal (hold depth vs. in-band economic target).\n"
    "    \"\"\"\n\n"
    "    def __init__(self, building_meta_data, action_spec):\n"
    "        super().__init__(building_meta_data, action_spec)\n"
    "        self.fade_h = 3.0\n"
    "        self.full_h = 12.0\n\n"
    + band_shift +
    "\n\nV6PolicyStandalone = V6Policy\n"
)
out = out.rstrip() + v6
(root / "policies/v6_policy.py").write_text(out)
print("wrote policies/v6_policy.py", len(out), "chars")
