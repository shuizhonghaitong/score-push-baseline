#!/usr/bin/env python3
"""Build self-contained policies/v5_policy.py = v4 policy + V4d (zone shift)."""
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
base = (root / "policies/v4_policy.py").read_text()
var = (root / "policies/v4_variants.py").read_text()

# Strip base docstring (replace with v5 docstring), keep import numpy.
m = re.match(r'^\s*"""(.*?)"""\s*\n', base, re.S)
base_code = base[m.end():].lstrip()

# Extract only the V4dPolicy class (stop at the next top-level class/alias).
i = var.find("class V4dPolicy")
j = var.find("\nclass ", i + 1)
k = var.find("\nV4", i + 1)
ends = [e for e in (j, k) if e != -1]
v4d = var[i:min(ends) if ends else None].strip()
v4d = v4d.replace("class V4dPolicy(V4Policy):", "class V5Policy(V4Policy):")
v4d = v4d.rstrip("\n") + "\n\nV5PolicyStandalone = V5Policy\n"

out = '"""V5 rule-based HVAC policy = V4 + per-zone economic target shift.\n\nGenerated by tools/build_v5.py; do not edit directly.\n"""\n' + base_code + "\n\n" + v4d + "\n"
(root / "policies/v5_policy.py").write_text(out)
print("wrote policies/v5_policy.py", len(out), "chars")
