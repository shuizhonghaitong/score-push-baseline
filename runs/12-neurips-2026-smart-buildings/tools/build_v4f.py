#!/usr/bin/env python3
"""Build self-contained policies/v4f_policy.py = v4 policy + V4f (pre-latch setback)."""
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
base = (root / "policies/v4_policy.py").read_text()
var = (root / "policies/v4_variants.py").read_text()

m = re.match(r'^\s*"""(.*?)"""\s*\n', base, re.S)
base_code = base[m.end():].lstrip()

i = var.find("class V4fPolicy")
v4f = var[i:].strip()
v4f = v4f.replace("class V4fPolicy(V4Policy):", "class V4fPolicyStandalone(V4Policy):")

out = '"""V4f rule-based HVAC policy = V4 + pre-latch setback.\n\nGenerated by tools/build_v4f.py; do not edit directly.\n"""\n' + base_code + "\n\n" + v4f + "\n"
(root / "policies/v4f_policy.py").write_text(out)
print("wrote policies/v4f_policy.py", len(out), "chars")
